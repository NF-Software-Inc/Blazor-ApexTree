namespace ApexTree;

/// <summary>
/// Vertical placement of an external node label relative to the node.
/// </summary>
public enum ExternalLabelVerticalAlign
{
	/// <summary>
	/// Label sits below the node (text is top-anchored).
	/// </summary>
	Bottom,

	/// <summary>
	/// Label is centered on the node vertically (default).
	/// </summary>
	Middle,

	/// <summary>
	/// Label sits above the node (text is bottom-anchored).
	/// </summary>
	Top
}
